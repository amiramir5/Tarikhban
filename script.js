function findNextSuggestedChapter() {
  for (let i = 0; i < CHAPTERS_DATA.length; i++) {
    if (gameState.completedChapters.indexOf(CHAPTERS_DATA[i].id) === -1) {
      return CHAPTERS_DATA[i];
    }
  }
  return CHAPTERS_DATA[0] || null;
}

