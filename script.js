function openChapterStory(chapterId) {
  const chapter = CHAPTERS_DATA.find(function (c) { return c.id === chapterId; });
  if (!chapter) return;

  currentChapterCache = chapter;
  gameState.currentChapterId = chapterId;
  gameState.isAnsweredCurrent = false;

  /* عنوان */
  const eraTag = document.getElementById('storyEraTag');
  const eraTitle = document.getElementById('storyEraTitle');
  const sceneContext = document.getElementById('storySceneContext');

  if (eraTag) eraTag.textContent = chapter.period + ' • واقعه‌نگاری زنده';
  if (eraTitle) eraTitle.textContent = chapter.title;
  if (sceneContext) sceneContext.textContent = chapter.context;

  /* سخنرانان */
  setSpeaker('A', chapter.speakerA);
  setSpeaker('B', chapter.speakerB);

  /* گفت‌وگو */
  const speakerLabel = document.getElementById('currentSpeakerLabel');
  const dialogueText = document.getElementById('dialogueText');
  const dialogueExplanation = document.getElementById('dialogueExplanation');

  if (speakerLabel) {
    speakerLabel.innerHTML =
      '<span class="dialogue-speaker-mark"></span>' +
      'کلامِ ' + escapeHtml(chapter.speakerA.name) + ' خطاب به ' + escapeHtml(chapter.speakerB.name) + ':';
  }
  if (dialogueText) dialogueText.textContent = chapter.dialogueQuote;
  if (dialogueExplanation) {
    dialogueExplanation.classList.add('is-hidden');
    dialogueExplanation.textContent = '';
  }

  /* دکمه‌ی نشان‌گذاری */
  const bookmarkBtn = document.getElementById('btnBookmark');
  if (bookmarkBtn) {
    if (isBookmarked(chapterId)) {
      bookmarkBtn.classList.add('is-bookmarked');
      bookmarkBtn.setAttribute('title', 'حذف از نشان‌شده‌ها');
    } else {
      bookmarkBtn.classList.remove('is-bookmarked');
      bookmarkBtn.setAttribute('title', 'نشان‌گذاری این فصل');
    }
  }

  /* یادداشت */
  const notesInput = document.getElementById('notesInput');
  if (notesInput) {
    notesInput.value = (gameState.notes && gameState.notes[chapterId]) || '';
    /* حذف شنونده‌های قبلی با شبیه‌سازی: ذخیره در data attribute */
    notesInput.dataset.chapterId = chapterId;
  }

  /* گزینه‌ها */
  renderOptions(chapter);

  /* پاک کردن بازخورد */
  const feedback = document.getElementById('feedbackPanel');
  if (feedback) {
    feedback.className = 'feedback-panel is-hidden';
    feedback.innerHTML = '';
  }

  showView('story');
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

